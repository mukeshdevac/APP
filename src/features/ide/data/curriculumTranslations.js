export function getLocalizedModule(module, lang = 'en') {
    if (!module) return null;
    if (lang === 'en') return module;

    const modTranslations = MODULE_TRANSLATIONS[module.id] || MODULE_TRANSLATIONS[module.exampleId];
    if (!modTranslations) return module;

    // Direct match, or fallback: ta_script falls back to ta, then default module
    const t = modTranslations[lang] || (lang === 'ta_script' ? modTranslations['ta'] : null);
    if (!t) return module;

    return {
        ...module,
        title: t.title || module.title,
        summary: t.summary || module.summary,
        overview: {
            what: t.what || module.overview?.what,
            howItWorks: t.howItWorks || module.overview?.howItWorks,
            realWorld: t.realWorld || module.overview?.realWorld
        },
        guruTip: t.guruTip || null,
        quiz: t.quiz || null,
        steps: t.steps || module.steps
    };
}
